"""Build offline presentation data from frozen repository evidence (stdlib only)."""
from pathlib import Path
from collections import Counter, defaultdict
import csv
import hashlib
import io
import json
import subprocess

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "presentation/js/chart-data.js"


def source(path):
    file = ROOT / path
    if file.exists():
        return file.read_bytes()
    # Allows regeneration from a partial clone with the evidence in Git's cache.
    return subprocess.check_output(["git", "show", "HEAD:" + path], cwd=ROOT)


def table(path, encoding="utf-8-sig"):
    return list(csv.DictReader(io.StringIO(source(path).decode(encoding))))


def read_json(path):
    return json.loads(source(path))


def main():
    paths = [
        "datasets/data_2026.csv", "datasets/splits/split_manifest.csv",
        "Assignment_Report_v2/analysis/results.json",
        "Assignment_Report_v2/analysis/deployment_explanations.json",
        "output/revision_v2/analysis/diagnostics.csv",
        "presentation/assets/evidence/temperature-analysis.json",
        "presentation/assets/evidence/application-check.json",
    ]
    raw = table(paths[0], "latin1")
    manifest = {int(r["data_row"]): r for r in table(paths[1])}
    counts = Counter(r["parent_group_id"] for r in manifest.values())
    names = defaultdict(set)
    for i, row in enumerate(raw, 1):
        names[manifest[i]["parent_group_id"]].add(row["Drug"])
    parents = sorted(counts, key=lambda k: (-counts[k], k))
    drugs = sorted({r["Drug SMILES"] for r in raw},
                   key=lambda k: (-sum(r["Drug SMILES"] == k for r in raw), k))
    solvents = sorted({r["Solvent SMILES"] for r in raw},
                      key=lambda k: (-sum(r["Solvent SMILES"] == k for r in raw), k))
    pair_counts = Counter((r["Drug SMILES"], r["Solvent SMILES"]) for r in raw)
    development = [r for i, r in enumerate(raw, 1) if manifest[i]["role"] == "development"]
    result = read_json(paths[2])
    explanations = read_json(paths[3])
    ablations = {r["tag"]: r for r in table(paths[4])}
    selected = [("no_balanced", "Equal row weights"), ("no_interaction", "Remove interactions"),
                ("no_temperature", "Remove temperature term"), ("full_gain", "Fix temperature gain at 1")]
    data = {
        "provenance": [{"path": p, "sha256": hashlib.sha256(source(p)).hexdigest()} for p in paths],
        "coverage": {
            "drugs": [next(r["Drug"] for r in raw if r["Drug SMILES"] == k) for k in drugs],
            "solvents": [next(r["Solvent"] for r in raw if r["Solvent SMILES"] == k) for k in solvents],
            "cells": [[drugs.index(d), solvents.index(s), n] for (d, s), n in pair_counts.items()],
        },
        "parents": [{"id": p, "name": ", ".join(sorted(names[p])), "count": counts[p]} for p in parents],
        "developmentTargets": [float(r["Solubility_log10"]) for r in development],
        "measurements": [{"drug": r["Drug"], "solvent": r["Solvent"],
                          "t": float(r["Temperature"]), "y": float(r["Solubility_log10"])} for r in raw],
        "results": result,
        "explanations": explanations,
        "solarAblation": [{"label": label, **{k: float(ablations["AdaptiveHybrid_" + key][k])
                           for k in ["parent_macro_MAE", "delta", "lower", "upper"]}} for key, label in selected],
        "temperature": read_json(paths[5]),
        "application": read_json(paths[6]),
        "responseObservations": [{"t": float(r["Temperature"]), "y": float(r["Solubility_log10"])}
                                 for r in development if r["Drug"] == "Lovastatin" and r["Solvent"] == "Butyl Acetate"],
    }
    assert len(raw) == 1904 and len(development) == 1507
    assert (len(drugs), len(solvents), len(pair_counts), len(parents)) == (168, 49, 646, 161)
    assert sum(counts[p] for p in parents[:30]) == 1078
    assert sum(1 for n in counts.values() if n <= 5) == 74
    assert len(data["responseObservations"]) == 20
    OUT.write_text("// Generated by presentation/tools/build_chart_data.py. Do not hand-edit.\n"
                   + "const SOLAR_DATA = " + json.dumps(data, ensure_ascii=True, separators=(",", ":")) + ";\n",
                   encoding="utf-8")
    print(f"Built {OUT.relative_to(ROOT)} ({OUT.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
